async def rewrite_text_with_gemini(text: str) -> str:
    """
    Автоматический рерайт текста новости/поста с помощью ИИ
    Проверяет на рекламу, скучный контент и дубликаты.
    Возвращает строку-результат, либо REJECT_AD, REJECT_BORING, DUPLICATE.
    """
    if not AI_API_KEY:
        logger.warning("AI_API_KEY не установлен. Рерайт пропущен.")
        return text
        
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key={AI_API_KEY}"
    
    custom_prompt = await get_setting("ai_prompt", DEFAULT_PROMPT)
    recent_summaries = await get_recent_summaries(10)
    
    recent_text = "\n".join([f"- {s}" for s in recent_summaries])
    dup_instruction = f"\n\nПроверь, публиковали ли мы эту новость ранее. Вот последние 10 наших постов:\n{recent_text}\nЕсли новость рассказывает об одном и том же событии из списка выше, ответь строго одним словом: DUPLICATE." if recent_summaries else ""
    
    full_prompt = (
        f"{custom_prompt}{dup_instruction}\n\n"
        "ОТВЕЧАЙ ТОЛЬКО ГОТОВЫМ ТЕКСТОМ ИЛИ СИСТЕМНЫМИ СЛОВАМИ (REJECT_AD, REJECT_BORING, DUPLICATE) БЕЗ ПРИВЕТСТВИЙ И ПОЯСНЕНИЙ.\n\n"
        f"Исходный текст поста:\n{text}"
    )
    
    payload = {
        "contents": [
            {
                "parts": [{"text": full_prompt}]
            }
        ]
    }
    
    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            response = await client.post(url, json=payload)
            if response.status_code == 200:
                data = response.json()
                result = data["candidates"][0]["content"]["parts"][0]["text"].strip()
                return result
            else:
                logger.error(f" API Error {response.status_code}: {response.text}")
                return text
    except Exception as e:
        logger.error(f"Ошибка при вызове API: {e}")
        return text
