    "7. ДИСКЛЕЙМЕРЫ И ПОМЕТКИ: Если в исходнике есть пометки о статусе лиц/организаций ('*Признан иноагентом в РФ', '*Внесен в список экстремистов' и т.д.), ты ОБЯЗАН перенести их в самый конец поста.\n\n"
    "Отвечай ТОЛЬКО готовым текстом для публикации ИЛИ одним словом REJECT_AD / REJECT_BORING."
